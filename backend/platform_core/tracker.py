"""The implementation tracker in backend/docs: parsing, validation and generated indexes.

The tracker is the single source of truth for what is built and what remains
(backend/docs/handover.md explains the format). `python manage.py check_tracker`
runs `check()` in CI so the documents cannot drift from the code:

- every phase file (roadmap/Pnn-*.md) has one phase table and one work-package
  table, with known statuses and IDs that belong to the phase;
- a done work package names its commit or pull request and at least one code
  path and one test path, and every one of those paths exists;
- a done phase contains only done or deferred work packages;
- every decision mentioned anywhere in the documents (D-001 …) has exactly one
  decision file, and a superseded decision names an existing replacement;
- every relative Markdown link points to an existing file;
- every backend module has a README.md;
- the generated ROADMAP.md and decisions/README.md are current.

`render_roadmap()` and `render_decision_index()` produce the two generated files.

`check_pull_request()` enforces the tracker on every pull request (D-038): the
title names a work package (or is a [Fix] / [CI] / [Docs] change), and code
changes arrive together with that work package's tracker update.
"""

import re
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field
from pathlib import Path

GENERATED_NOTE = "<!-- Generated by `python manage.py check_tracker --write`. Do not edit by hand. -->"

STATUSES = {
    "⬜": "Pending",
    "🔄": "In progress",
    "👀": "In review",
    "✅": "Done",
    "⛔": "Blocked",
    "⏸": "Deferred",
}
DONE = "✅"
DEFERRED = "⏸"
DECISION_STATUSES = {"✅": "Confirmed", "🟡": "Assumed", "📝": "Proposed", "♻": "Superseded"}
SUPERSEDED = "♻"

PHASE_FILE = re.compile(r"^P(\d{2})-[a-z0-9-]+\.md$")
DECISION_FILE = re.compile(r"^(D-\d{3})-[a-z0-9-]+\.md$")
DECISION_ID = re.compile(r"\bD-\d{3}\b")
PACKAGE_ID = re.compile(r"^P(\d+)\.(\d+)$")
HEADING = re.compile(r"^(#{1,6})\s+(.*)$")
CODE_SPAN = re.compile(r"`([^`]+)`")
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
EMPTY_CELLS = {"", "-", "—"}
LOG_ENTRY = re.compile(r"^- (\d{4}-\d{2}-\d{2}) · ([^·]+?) · ([^·]+?) · (.+)$")
RECENT_ENTRIES = 8
TITLE_TAG = re.compile(r"\[([^\]]+)\]")
PHASE_OR_PACKAGE = re.compile(r"^P\d+(\.\d+)?$")
# Pull requests that are not roadmap work: no tracker row to update.
FREE_TAGS = {"fix", "ci", "docs"}
# A work package counts as delivered in its pull request once its row says one of these.
DELIVERED = {"👀", "✅"}


@dataclass
class LogEntry:
    date: str
    packages: str
    reference: str
    text: str
    order: int


@dataclass
class Table:
    line: int
    header: list[str]
    rows: list[tuple[int, list[str]]]


@dataclass
class WorkPackage:
    id: str
    title: str
    status: str
    owner: str
    depends_on: str
    reference: str
    line: int
    code: list[str] = field(default_factory=list)
    tests: list[str] = field(default_factory=list)


@dataclass
class Phase:
    id: str
    name: str
    path: Path
    status: str = ""
    status_text: str = ""
    owner: str = ""
    needs: str = ""
    decisions: str = ""
    unlocks: str = ""
    packages: list[WorkPackage] = field(default_factory=list)
    log: list[LogEntry] = field(default_factory=list)


@dataclass
class Decision:
    id: str
    title: str
    path: Path
    status: str = ""
    status_text: str = ""
    date: str = ""
    phase: str = ""


def status_symbol(cell: str) -> str:
    """The status emoji a cell starts with ("" if none); variation selectors ignored."""
    text = cell.replace("️", "").strip()
    return text[:1]


def _cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def parse_tables(text: str) -> list[Table]:
    """Markdown tables in `text`, with 1-based line numbers."""
    tables: list[Table] = []
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        is_table = (
            line.lstrip().startswith("|")
            and index + 1 < len(lines)
            and re.match(r"^\s*\|[\s:|-]+\|?\s*$", lines[index + 1])
        )
        if not is_table:
            index += 1
            continue
        table = Table(line=index + 1, header=_cells(line), rows=[])
        index += 2
        while index < len(lines) and lines[index].lstrip().startswith("|"):
            table.rows.append((index + 1, _cells(lines[index])))
            index += 1
        tables.append(table)
    return tables


def _title(text: str) -> str:
    for line in text.splitlines():
        match = HEADING.match(line)
        if match and len(match.group(1)) == 1:
            return match.group(2).strip()
    return ""


def _after_dash(title: str) -> str:
    return title.split("—", 1)[1].strip() if "—" in title else title


def _sections(text: str) -> Iterator[tuple[str, list[str]]]:
    """(heading text, body lines) for every level-3 heading."""
    heading: str | None = None
    body: list[str] = []
    for line in text.splitlines():
        match = HEADING.match(line)
        if match and len(match.group(1)) <= 3:
            if heading is not None:
                yield heading, body
            heading = match.group(2).strip() if len(match.group(1)) == 3 else None
            body = []
        elif heading is not None:
            body.append(line)
    if heading is not None:
        yield heading, body


def _paths(body: Iterable[str], label: str) -> list[str]:
    prefix = f"- **{label}:**"
    paths: list[str] = []
    for line in body:
        if line.strip().startswith(prefix):
            paths.extend(CODE_SPAN.findall(line))
    return paths


def parse_phase(path: Path, problems: list[str], docs_dir: Path) -> Phase | None:
    match = PHASE_FILE.match(path.name)
    if not match:
        return None
    where = path.relative_to(docs_dir).as_posix()
    text = path.read_text(encoding="utf-8")
    phase = Phase(id=f"P{int(match.group(1))}", name=_after_dash(_title(text)), path=path)
    tables = parse_tables(text)

    phase_tables = [t for t in tables if t.header[:1] == ["Phase"]]
    if len(phase_tables) != 1 or len(phase_tables[0].rows) != 1:
        problems.append(f"{where}: needs exactly one phase table (| Phase | Status | Owner | …) with one row.")
    else:
        line, row = phase_tables[0].rows[0]
        row = [*row, "", "", "", "", "", ""][:6]
        if row[0] != phase.id:
            problems.append(f"{where}:{line}: the phase table says {row[0]!r}; the file name says {phase.id}.")
        phase.status, phase.status_text = status_symbol(row[1]), row[1]
        phase.owner, phase.needs, phase.decisions, phase.unlocks = row[2], row[3], row[4], row[5]
        if phase.status not in STATUSES:
            problems.append(f"{where}:{line}: unknown phase status {row[1]!r}.")

    package_tables = [t for t in tables if t.header[:1] == ["ID"]]
    if len(package_tables) != 1:
        problems.append(f"{where}: needs exactly one work-package table (| ID | Work package | Status | …).")
        return phase
    seen: set[str] = set()
    for line, row in package_tables[0].rows:
        row = [*row, "", "", "", "", "", ""][:6]
        package = WorkPackage(
            id=row[0],
            title=row[1],
            status=status_symbol(row[2]),
            owner=row[3],
            depends_on=row[4],
            reference=row[5],
            line=line,
        )
        id_match = PACKAGE_ID.match(package.id)
        if not id_match or f"P{int(id_match.group(1))}" != phase.id:
            problems.append(f"{where}:{line}: work package {package.id!r} does not belong to {phase.id}.")
        if package.id in seen:
            problems.append(f"{where}:{line}: work package {package.id} is listed twice.")
        seen.add(package.id)
        if package.status not in STATUSES:
            problems.append(f"{where}:{line}: {package.id} has an unknown status {row[2]!r}.")
        phase.packages.append(package)

    details = {heading.split()[0]: body for heading, body in _sections(text) if heading}
    for package in phase.packages:
        body = details.get(package.id, [])
        package.code, package.tests = _paths(body, "Code"), _paths(body, "Tests")
    phase.log = _progress_log(text)
    return phase


def _progress_log(text: str) -> list[LogEntry]:
    """Entries of the '## Progress log' section: `- date · packages · reference · text`."""
    entries: list[LogEntry] = []
    in_log = False
    for line in text.splitlines():
        heading = HEADING.match(line)
        if heading:
            in_log = len(heading.group(1)) == 2 and heading.group(2).strip().lower() == "progress log"
            continue
        match = LOG_ENTRY.match(line.strip()) if in_log else None
        if match:
            date, packages, reference, entry = (part.strip() for part in match.groups())
            entries.append(LogEntry(date, packages, reference, entry, order=len(entries)))
    return entries


def parse_decision(path: Path, problems: list[str], docs_dir: Path) -> Decision | None:
    match = DECISION_FILE.match(path.name)
    if not match:
        return None
    where = path.relative_to(docs_dir).as_posix()
    text = path.read_text(encoding="utf-8")
    title = _title(text)
    decision = Decision(id=match.group(1), title=_after_dash(title), path=path)
    if not title.startswith(decision.id):
        problems.append(f"{where}: the title must start with {decision.id}.")
    fields = {
        row[0]: row[1]
        for table in parse_tables(text)
        if table.header[:2] == ["Field", "Value"]
        for _, row in table.rows
        if len(row) >= 2
    }
    decision.status_text = fields.get("Status", "")
    decision.status = status_symbol(decision.status_text)
    decision.date, decision.phase = fields.get("Date", ""), fields.get("Phase", "")
    if decision.status not in DECISION_STATUSES:
        problems.append(f"{where}: unknown decision status {decision.status_text!r}.")
    return decision


def _check_paths(phase: Phase, repo_root: Path, docs_dir: Path, problems: list[str]) -> None:
    where = phase.path.relative_to(docs_dir).as_posix()
    for package in phase.packages:
        if package.status != DONE:
            continue
        if package.reference in EMPTY_CELLS:
            problems.append(f"{where}:{package.line}: {package.id} is done but names no commit or pull request.")
        if not package.code:
            problems.append(f"{where}:{package.line}: {package.id} is done but lists no code path (- **Code:**).")
        if not package.tests:
            problems.append(f"{where}:{package.line}: {package.id} is done but lists no test path (- **Tests:**).")
        for listed in package.code + package.tests:
            if not (repo_root / listed).exists():
                problems.append(f"{where}: {package.id} points to {listed}, which does not exist.")
    open_packages = [p.id for p in phase.packages if p.status not in (DONE, DEFERRED)]
    if phase.status == DONE and open_packages:
        problems.append(f"{where}: {phase.id} is marked done but {', '.join(open_packages)} are not.")


def _check_links(files: Iterable[Path], repo_root: Path, problems: list[str]) -> None:
    for path in files:
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            for target in LINK.findall(line):
                if target.startswith(("http://", "https://", "mailto:", "#")):
                    continue
                relative = target.split("#", 1)[0]
                if relative and not (path.parent / relative).exists():
                    where = path.relative_to(repo_root).as_posix()
                    problems.append(f"{where}:{number}: the link to {relative} points to nothing.")


def render_roadmap(phases: list[Phase]) -> str:
    lines = [
        "# Roadmap — P0 to P13",
        "",
        GENERATED_NOTE,
        "",
        "One row per phase, built from the phase files in [roadmap/](roadmap). Requirements,",
        "dependencies, acceptance criteria and evidence are in each phase file.",
        "",
        "Status: " + " · ".join(f"{symbol} {name}" for symbol, name in STATUSES.items()),
        "",
        "## Overall",
        "",
        _overall("Phase 1 (P0 to P12)", [p for p in phases if int(p.id[1:]) <= 12]),
        _overall("Whole roadmap (P0 to P13)", phases),
        "",
        "## Phases",
        "",
        "| Phase | Name | Status | Work packages done | Owner | Needs | Decisions | Unlocks |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for phase in phases:
        done, total = _counts([phase])
        link = f"[{phase.name}](roadmap/{phase.path.name})"
        lines.append(
            f"| {phase.id} | {link} | {phase.status_text} | {done} / {total} | {phase.owner} "
            f"| {phase.needs} | {phase.decisions} | {phase.unlocks} |"
        )
    lines += ["", "## Recently completed", "", "Newest first, from the phase files' progress logs.", ""]
    recent = sorted(
        ((entry, phase) for phase in phases for entry in phase.log),
        key=lambda item: (item[0].date, int(item[1].id[1:]), item[0].order),
        reverse=True,
    )[:RECENT_ENTRIES]
    for entry, phase in recent:
        link = f"[{phase.id}](roadmap/{phase.path.name})"
        lines.append(f"- {entry.date} · {link} · {entry.packages} · {entry.reference} · {_shorten(entry.text)}")
    if not recent:
        lines.append("- Nothing yet.")
    return "\n".join(lines) + "\n"


def _counts(phases: Iterable[Phase]) -> tuple[int, int]:
    """(done, total) work packages; deferred ones count in the phase they moved to."""
    counted = [p for phase in phases for p in phase.packages if p.status != DEFERRED]
    return sum(p.status == DONE for p in counted), len(counted)


def _overall(label: str, phases: list[Phase]) -> str:
    done, total = _counts(phases)
    percent = round(100 * done / total) if total else 0
    return f"- **{label}:** {done} of {total} work packages done ({percent}%)"


def _shorten(text: str, limit: int = 110) -> str:
    first = re.split(r"(?<=[.;])\s", text, maxsplit=1)[0]
    return first if len(first) <= limit else first[: limit - 1].rstrip() + "…"


def render_decision_index(decisions: list[Decision]) -> str:
    lines = [
        "# Decisions",
        "",
        GENERATED_NOTE,
        "",
        "One file per decision. To add one, copy [_template.md](_template.md) to the next free",
        "number, then run `python manage.py check_tracker --write` to refresh this list.",
        "",
        "Status: " + " · ".join(f"{symbol} {name}" for symbol, name in DECISION_STATUSES.items()),
        "",
        "| ID | Decision | Status | Phase | Date |",
        "|---|---|---|---|---|",
    ]
    for decision in decisions:
        link = f"[{decision.title}]({decision.path.name})"
        lines.append(f"| {decision.id} | {link} | {decision.status_text} | {decision.phase} | {decision.date} |")
    return "\n".join(lines) + "\n"


@dataclass
class Result:
    problems: list[str]
    roadmap: str
    decision_index: str


def load_phases(docs_dir: Path, problems: list[str]) -> list[Phase]:
    """Every phase file, in phase order (parsing problems are appended to `problems`)."""
    phases = [
        phase
        for path in sorted((docs_dir / "roadmap").glob("*.md"))
        if (phase := parse_phase(path, problems, docs_dir)) is not None
    ]
    return sorted(phases, key=lambda phase: int(phase.id[1:]))


def _is_code(path: str) -> bool:
    """A changed file that is product code or tests (not documentation)."""
    return path.startswith(("backend/", "frontend/")) and not path.endswith(".md")


def check_pull_request(title: str, changed_files: Iterable[str], docs_dir: Path, repo_root: Path) -> list[str]:
    """Problems with a pull request's title and tracker updates (empty list: it may merge).

    - The title carries one or more tags in brackets: work packages ("[P3.2]"), whole phases
      ("[P2]"), or "[Fix]", "[CI]", "[Docs]" for changes that are not roadmap work.
    - Every named work package or phase exists in the tracker.
    - If the pull request changes code, each named item's phase file is changed in the same
      pull request, and the item says 👀 In review or ✅ Done there.
    - A "[Docs]"-only pull request changes no code.
    """
    files = [line.strip().replace("\\", "/") for line in changed_files if line.strip()]
    code = sorted(path for path in files if _is_code(path))
    tags = [tag.strip() for tag in TITLE_TAG.findall(title)]
    items = [tag.upper() for tag in tags if PHASE_OR_PACKAGE.match(tag.upper())]
    free = {tag.lower() for tag in tags} & FREE_TAGS
    example = "for example '[P3.2] Policy engine', or '[Fix] …', '[CI] …', '[Docs] …' for other changes"

    if not items and not free:
        return [f"The title must name the work package it delivers, {example}."]
    problems: list[str] = []
    if free == {"docs"} and not items and code:
        shown = ", ".join(code[:5])
        problems.append(f"A [Docs] pull request must not change code, but it changes {shown}.")
    if not items:
        return problems

    load_problems: list[str] = []
    phases = {phase.id: phase for phase in load_phases(docs_dir, load_problems)}
    changed = set(files)
    for item in items:
        phase = phases.get(item.split(".")[0])
        package = next((p for p in phase.packages if p.id == item), None) if phase else None
        if phase is None or ("." in item and package is None):
            problems.append(f"{item} is not in the tracker. Add its row to the phase file first, then use its ID.")
            continue
        if not code:
            continue
        phase_file = phase.path.relative_to(repo_root).as_posix()
        if phase_file not in changed:
            problems.append(
                f"This pull request changes code for {item}, but {phase_file} was not updated. "
                f"Set {item} to ✅ Done (or 👀 In review) and list its code and test paths."
            )
            continue
        status, text = (package.status, item) if package else (phase.status, f"the {item} phase table")
        if status not in DELIVERED:
            problems.append(f"{item} still says it is not delivered: set {text} to ✅ Done or 👀 In review.")
    return problems


def check(docs_dir: Path, repo_root: Path, module_dirs: Iterable[Path]) -> Result:
    """Validate the tracker. `module_dirs` are the backend modules that need a README."""
    problems: list[str] = []

    phases = load_phases(docs_dir, problems)
    for phase in phases:
        _check_paths(phase, repo_root, docs_dir, problems)

    decisions: list[Decision] = []
    for path in sorted((docs_dir / "decisions").glob("D-*.md")):
        decision = parse_decision(path, problems, docs_dir)
        if decision is None:
            problems.append(f"decisions/{path.name}: decision files are named D-nnn-short-title.md.")
        else:
            decisions.append(decision)
    by_id: dict[str, Decision] = {}
    for decision in decisions:
        if decision.id in by_id:
            problems.append(f"decisions: {decision.id} is used by two files; give the newer one the next free number.")
        by_id[decision.id] = decision
    for decision in decisions:
        if decision.status == SUPERSEDED:
            replacements = DECISION_ID.findall(decision.status_text)
            if not replacements or any(r not in by_id for r in replacements):
                problems.append(f"decisions/{decision.path.name}: say which existing decision supersedes it.")

    documents = sorted(docs_dir.rglob("*.md"))
    modules = list(module_dirs)
    module_readmes = [module / "README.md" for module in modules]
    for module, readme in zip(modules, module_readmes, strict=True):
        if not readme.exists():
            problems.append(f"{module.name}/README.md is missing: every module documents itself (handover.md).")
    existing_readmes = [readme for readme in module_readmes if readme.exists()]
    for path in documents + existing_readmes:
        for mentioned in sorted(set(DECISION_ID.findall(path.read_text(encoding="utf-8")))):
            if mentioned not in by_id:
                where = path.relative_to(repo_root).as_posix()
                problems.append(f"{where}: mentions {mentioned}, which has no file in decisions/.")
    top_readmes = [p for p in (repo_root / "README.md", repo_root / "backend" / "README.md") if p.exists()]
    _check_links(documents + existing_readmes + top_readmes, repo_root, problems)

    return Result(
        problems=problems,
        roadmap=render_roadmap(phases),
        decision_index=render_decision_index(sorted(decisions, key=lambda d: d.id)),
    )
