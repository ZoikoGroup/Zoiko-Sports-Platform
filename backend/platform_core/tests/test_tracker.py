PHASE = """# P1 — Kernel

| Phase | Status | Owner | Needs | Decisions | Unlocks |
|---|---|---|---|---|---|
| P1 | {phase_status} | A | P0 | D-001 | Everything |

| ID | Work package | Status | Owner | Depends on | PR / commit |
|---|---|---|---|---|---|
| P1.1 | Records | {status} | A | — | {reference} |
| P1.2 | Later | ⏸ Deferred | A | — | → P2 |

### P1.1 Records
- **Code:** {code}
- **Tests:** {tests}
- Planned code: `backend/not_built_yet.py` (not checked)

### P1.2 Later
- Nothing yet.

## Progress log

- 2026-11-20 · P1.1 · abc1234 · records built; next: more. Later sentence.
- (not an entry: no date)
"""

DECISION = """# {id} — {title}

| Field | Value |
|---|---|
| Status | {status} |
| Date | 2026-11-26 |
| Phase | P1 |
"""


class TrackerTestCase(SimpleTestCase):
    def setUp(self) -> None:
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        self.docs = self.root / "backend" / "docs"
        (self.docs / "roadmap").mkdir(parents=True)
        (self.docs / "decisions").mkdir()
        # The generated decision index links to the template.
        (self.docs / "decisions" / "_template.md").write_text("# D-nnn — Template\n", encoding="utf-8")
        self.module = self.root / "backend" / "kernel"
        self.module.mkdir()
        (self.module / "README.md").write_text("# kernel\n", encoding="utf-8")
        (self.module / "models.py").write_text("", encoding="utf-8")
        (self.module / "tests.py").write_text("", encoding="utf-8")
        self.write_decision("D-001", "First", "✅ Confirmed")
        self.write_phase()

    def write_phase(
        self,
        *,
        phase_status: str = "✅ Done",
        status: str = "✅ Done",
        reference: str = "abc1234",
        code: str = "`backend/kernel/models.py`",
        tests: str = "`backend/kernel/tests.py`",
        name: str = "P01-kernel.md",
    ) -> None:
        text = PHASE.format(phase_status=phase_status, status=status, reference=reference, code=code, tests=tests)
        (self.docs / "roadmap" / name).write_text(text, encoding="utf-8")

    def write_decision(self, id_: str, title: str, status: str, slug: str = "") -> None:
        name = f"{id_}-{slug or title.lower()}.md"
        (self.docs / "decisions" / name).write_text(DECISION.format(id=id_, title=title, status=status), "utf-8")

    def problems(self) -> list[str]:
        return check(self.docs, self.root, [self.module]).problems

    def assertProblem(self, fragment: str) -> None:
        problems = self.problems()
        self.assertTrue(any(fragment in p for p in problems), f"{fragment!r} not in {problems}")


class ParsingTests(SimpleTestCase):
    def test_status_symbol_ignores_variation_selectors(self):
        self.assertEqual(status_symbol("⏸️ Deferred"), "⏸")
        self.assertEqual(status_symbol("  ✅ Done"), "✅")
        self.assertEqual(status_symbol(""), "")

    def test_tables_with_line_numbers(self):
        text = "intro\n\n| A | B |\n|---|---|\n| 1 | 2 |\n| 3 | 4 |\n\n| not a table |\n"
        [table] = parse_tables(text)
        self.assertEqual(table.header, ["A", "B"])
        self.assertEqual(table.rows, [(5, ["1", "2"]), (6, ["3", "4"])])


