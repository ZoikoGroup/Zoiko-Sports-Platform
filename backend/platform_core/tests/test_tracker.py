class WorkPackageTests(TrackerTestCase):
    def test_done_package_needs_a_commit(self):
        self.write_phase(reference="—")
        self.assertProblem("P1.1 is done but names no commit or pull request")

    def test_done_package_needs_code_and_test_paths(self):
        self.write_phase(code="", tests="")
        self.assertProblem("P1.1 is done but lists no code path")
        self.assertProblem("P1.1 is done but lists no test path")

    def test_listed_paths_must_exist(self):
        self.write_phase(tests="`backend/kernel/tests_gone.py`")
        self.assertProblem("P1.1 points to backend/kernel/tests_gone.py, which does not exist")

    def test_done_phase_with_open_packages(self):
        self.write_phase(status="🔄 In progress")
        self.assertProblem("P1 is marked done but P1.1 are not")

    def test_unknown_statuses(self):
        self.write_phase(phase_status="Finished", status="Started")
        self.assertProblem("unknown phase status 'Finished'")
        self.assertProblem("P1.1 has an unknown status 'Started'")

    def test_package_must_belong_to_its_phase_and_be_listed_once(self):
        text = PHASE.format(phase_status="⬜ Pending", status="⬜ Pending", reference="", code="", tests="")
        text = text.replace("| P1.2 | Later", "| P1.1 | Later").replace("| P1 | ⬜", "| P7 | ⬜")
        (self.docs / "roadmap" / "P01-kernel.md").write_text(text, encoding="utf-8")
        (self.docs / "roadmap" / "P02-next.md").write_text(
            "# P2 — Next\n\n| Phase | Status |\n|---|---|\n| P2 | ⬜ Pending |\n\n"
            "| ID | Work package | Status |\n|---|---|---|\n| P3.1 | Wrong | ⬜ |\n",
            encoding="utf-8",
        )
        self.assertProblem("the phase table says 'P7'; the file name says P1")
        self.assertProblem("work package P1.1 is listed twice")
        self.assertProblem("work package 'P3.1' does not belong to P2")

    def test_phase_file_needs_both_tables(self):
        (self.docs / "roadmap" / "P03-empty.md").write_text("# P3 — Empty\n", encoding="utf-8")
        self.assertProblem("P03-empty.md: needs exactly one phase table")
        self.assertProblem("P03-empty.md: needs exactly one work-package table")

    def test_other_markdown_in_roadmap_is_ignored(self):
        (self.docs / "roadmap" / "notes.md").write_text("Free notes.\n", encoding="utf-8")
        self.assertEqual(self.problems(), [])


