class CommandTests(TrackerTestCase):
    def run_command(self, *args: str) -> tuple[str, str]:
        out, err = StringIO(), StringIO()
        with override_settings(BASE_DIR=self.root / "backend"):
            call_command("check_tracker", *args, "--docs", str(self.docs), stdout=out, stderr=err)
        return out.getvalue(), err.getvalue()

    def test_write_creates_generated_files_then_check_passes(self):
        out, _ = self.run_command("--write")
        self.assertIn("Rewrote ROADMAP.md", out)
        self.assertIn("Rewrote decisions/README.md", out)
        self.assertTrue((self.docs / "ROADMAP.md").exists())
        out, _ = self.run_command()
        self.assertIn("Tracker OK", out)

    def test_stale_generated_file_fails(self):
        self.run_command("--write")
        (self.docs / "ROADMAP.md").write_text("edited by hand\n", encoding="utf-8")
        with self.assertRaisesMessage(CommandError, "1 problem(s)"):
            self.run_command()

    def test_windows_line_endings_are_not_stale(self):
        self.run_command("--write")
        roadmap = self.docs / "ROADMAP.md"
        roadmap.write_bytes(roadmap.read_bytes().replace(b"\n", b"\r\n"))
        out, _ = self.run_command()
        self.assertIn("Tracker OK", out)

    def test_problems_are_listed(self):
        self.write_phase(reference="")
        out, err = StringIO(), StringIO()
        with override_settings(BASE_DIR=self.root / "backend"), self.assertRaises(CommandError):
            call_command("check_tracker", "--write", "--docs", str(self.docs), stdout=out, stderr=err)
        self.assertIn("names no commit or pull request", err.getvalue())

    def test_missing_tracker(self):
        with override_settings(BASE_DIR=self.root / "backend"), self.assertRaisesMessage(CommandError, "No tracker"):
            call_command("check_tracker", "--docs", str(self.root / "nowhere"))

    def test_backend_modules_are_the_installed_project_apps(self):
        modules = {path.name for path in backend_modules(Path(settings.BASE_DIR).resolve())}
        self.assertTrue({"accounts", "organizations", "platform_core"} <= modules)
        self.assertNotIn("reference", modules)  # test-only module
        self.assertNotIn("auth", modules)  # Django's own apps live outside the project


class RoadmapProgressTests(TrackerTestCase):
    def test_overall_lines_count_every_phase(self):
        roadmap = check(self.docs, self.root, [self.module]).roadmap
        self.assertIn("- **Phase 1 (P0 to P12):** 1 of 1 work packages done (100%)", roadmap)
        self.assertIn("- **Whole roadmap (P0 to P13):** 1 of 1 work packages done (100%)", roadmap)

    def test_recently_completed_is_newest_first_and_shortened(self):
        (self.docs / "roadmap" / "P02-next.md").write_text(
            "# P2 — Next\n\n| Phase | Status |\n|---|---|\n| P2 | ⬜ Pending |\n\n"
            "| ID | Work package | Status |\n|---|---|---|\n| P2.1 | Next | ⬜ Pending |\n\n"
            "## Progress log\n\n- 2026-11-25 · P2.1 · PR #7 · " + "x" * 200 + "\n",
            encoding="utf-8",
        )
        roadmap = check(self.docs, self.root, [self.module]).roadmap
        recent = roadmap.split("## Recently completed", 1)[1]
        newest, older = recent.index("2026-11-25"), recent.index("2026-11-20")
        self.assertLess(newest, older)
        self.assertIn("[P1](roadmap/P01-kernel.md) · P1.1 · abc1234 · records built;", recent)
        self.assertNotIn("Later sentence", recent)
        self.assertIn("x" * 100 + "…", recent)
        self.assertIn("- **Whole roadmap (P0 to P13):** 1 of 2 work packages done (50%)", roadmap)

    def test_no_entries_yet(self):
        text = (self.docs / "roadmap" / "P01-kernel.md").read_text(encoding="utf-8")
        (self.docs / "roadmap" / "P01-kernel.md").write_text(text.split("## Progress log")[0], encoding="utf-8")
        self.assertIn("- Nothing yet.", check(self.docs, self.root, [self.module]).roadmap)


class PullRequestTests(TrackerTestCase):
    PHASE_FILE = "backend/docs/roadmap/P01-kernel.md"
    CODE = "backend/kernel/models.py"

    def pr(self, title: str, *changed: str) -> list[str]:
        return check_pull_request(title, list(changed), self.docs, self.root)

    def test_title_must_name_the_work(self):
        [problem] = self.pr("Policy engine", self.CODE)
        self.assertIn("must name the work package", problem)
        [problem] = self.pr("[WIP] Policy engine", self.CODE)
        self.assertIn("must name the work package", problem)

    def test_fix_and_ci_need_no_tracker_row(self):
        self.assertEqual(self.pr("[Fix] Typo in error message", self.CODE), [])
        self.assertEqual(self.pr("[ci] Faster pipeline", ".github/workflows/ci.yml", self.CODE), [])

    def test_docs_pull_request_must_not_change_code(self):
        self.assertEqual(self.pr("[Docs] Clarify handover", "backend/docs/handover.md", "README.md"), [])
        [problem] = self.pr("[Docs] Clarify handover", "backend/docs/handover.md", self.CODE)
        self.assertIn("must not change code, but it changes backend/kernel/models.py", problem)

    def test_unknown_work_package_or_phase(self):
        problems = self.pr("[P1.9][P7] Something", self.CODE)
        self.assertEqual(len(problems), 2)
        self.assertIn("P1.9 is not in the tracker", problems[0])
        self.assertIn("P7 is not in the tracker", problems[1])

    def test_code_without_tracker_update_is_refused(self):
        [problem] = self.pr("[P1.1] Records", self.CODE)
        self.assertIn("changes code for P1.1, but backend/docs/roadmap/P01-kernel.md was not updated", problem)

    def test_code_with_delivered_row_passes(self):
        self.assertEqual(self.pr("[P1.1] Records", self.CODE, self.PHASE_FILE), [])
        self.write_phase(status="👀 In review", phase_status="🔄 In progress")
        self.assertEqual(self.pr("[p1.1] Records", self.CODE, self.PHASE_FILE), [])

    def test_row_still_pending_is_refused(self):
        self.write_phase(status="🔄 In progress", phase_status="🔄 In progress")
        [problem] = self.pr("[P1.1] Records", self.CODE, self.PHASE_FILE)
        self.assertIn("P1.1 still says it is not delivered", problem)

    def test_whole_phase_uses_the_phase_status(self):
        self.assertEqual(self.pr("[P1] Kernel", self.CODE, self.PHASE_FILE), [])
        self.write_phase(phase_status="🔄 In progress", status="🔄 In progress")
        [problem] = self.pr("[P1] Kernel", self.CODE, self.PHASE_FILE)
        self.assertIn("set the P1 phase table to ✅ Done", problem)

    def test_tracker_only_pull_request_needs_no_status(self):
        self.write_phase(status="🔄 In progress", phase_status="🔄 In progress")
        self.assertEqual(self.pr("[P1.1] Claim the task", self.PHASE_FILE), [])

    def test_windows_paths_and_blank_lines(self):
        changed = [r"backend\kernel\models.py", "", r"backend\docs\roadmap\P01-kernel.md"]
        self.assertEqual(check_pull_request("[P1.1] Records", changed, self.docs, self.root), [])


class PullRequestCommandTests(TrackerTestCase):
    def run_command(self, *args: str, stdin: str = "") -> str:
        out, err = StringIO(), StringIO()
        with override_settings(BASE_DIR=self.root / "backend"), patch("sys.stdin", StringIO(stdin)):
            call_command("check_pull_request", *args, "--docs", str(self.docs), stdout=out, stderr=err)
        return out.getvalue() + err.getvalue()

    def test_changed_files_from_a_file(self):
        listing = self.root / "changed.txt"
        listing.write_text("backend/kernel/models.py\nbackend/docs/roadmap/P01-kernel.md\n", encoding="utf-8")
        self.assertIn("Pull request OK", self.run_command("--title", "[P1.1] Records", "--changed-files", str(listing)))

    def test_changed_files_from_standard_input(self):
        output = self.run_command("--title", "[P1.1] Records", stdin="backend/docs/roadmap/P01-kernel.md\n")
        self.assertIn("Pull request OK", output)

    def test_problems_fail_the_command(self):
        err = StringIO()
        with (
            override_settings(BASE_DIR=self.root / "backend"),
            patch("sys.stdin", StringIO("backend/kernel/models.py\n")),
            self.assertRaisesMessage(CommandError, "does not update the tracker"),
        ):
            call_command("check_pull_request", "--title", "[P1.1] x", "--docs", str(self.docs), stderr=err)
        self.assertIn("was not updated", err.getvalue())

    def test_unreadable_changed_files(self):
        with self.assertRaisesMessage(CommandError, "Cannot read the changed-files list"):
            self.run_command("--title", "[Fix] x", "--changed-files", str(self.root / "missing.txt"))
